"""Derives the claims for the counts the site states about its own files, on the pattern of scripts/energy_claims.py, so each count carries a claim id, a date, a boundary, and a limit.

Reads   site/data/library.json, site/data/policy-watch.json, site/data/whats-new.json, and the checklists in site/data-centers/index.html
Writes  work/site-refresh/evidence/site-counts.json, the local evidence file, then site/data/claims/site-counts.json

    python scripts/build_library_strip.py       (the Library page's bars and their marks; a merge runs this one for you)
    python scripts/site_count_claims.py
    python scripts/build_explorer.py            (home's figures and their limits; it stops if a figure and its claim differ)
    python scripts/pour_claim_refs.py --page site/library/index.html --page site/index.html

A count of a file is partly verified: the arithmetic is exact, but the file is curated, so each carries a limit written for the public. scripts/build_library_strip.py holds the Library's list of
counts and its claim ids, so a bar and its claim cannot differ, and validate_public.py fails a mark whose figure its claim does not hold. Standard library only.
"""
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_library_strip as strip  # noqa: E402
import build_plates as bp  # noqa: E402
import build_whats_new as wn  # noqa: E402
import energy_claims as ec  # noqa: E402
import validate_public as vp  # noqa: E402

CURATED = "A count of a curated file on its stated date: what this library holds, not all that is published."
DATED = "The stated date is the file's own update date, not a date of publication."  # in every library limit
LIVE = "Until this edition is published, the file's live address serves the earlier 10/29/2026 edition."  # ends every library limit until go-live
LIMITS = {
    "total": CURATED,
    "tribal": f"{CURATED} Tribal-specific is the library's own label for a source; it does not mean any Nation reviewed or endorsed that source.",
    "grounding": f"{CURATED} A core source is the library's own mark.",
    "several": f"{CURATED} An entry's areas are the library's own labels.",
    "area": f"{CURATED} An entry can list several areas, so area counts add to more than the whole.",
    "type": f"{CURATED} An entry's type is the library's own label.",
    "year": f"{CURATED} A year comes from the date on each entry, which may be a publication date, a latest update, or an event's own date.",
}
PENDING = ("Generated by scripts/site_count_claims.py. Quote and counts are from the library.json this release ships (site/data/library.json). "
           "On 11/05/2026 the live address still served the 10/29/2026 edition (414 entries). After go-live, fetch the live file, confirm updated is 2026-11-05, "
           "recount with build_library_strip.counts, then delete this note and the LIVE sentence.")
RES_2541 = {"title": "Resolution #2025-41: Establishing an Affiliated Tribes of Northwest Indians (ATNI) Task Force on Data Centers", "publisher": "Affiliated Tribes of Northwest Indians",
            "url": "https://atnitribes.org/wp-content/uploads/2025/11/20251016_25-41_TASK%20FORCE%20DATA%20CENTERS.pdf", "published": "2025-10", "kind": "organization"}
RES_2541_QUOTE = "The foregoing Resolution was adopted at the Affiliated Tribes of Northwest Indians 2025 Annual Convention held at the Suquamish Clearwater Casino Resort in Suquamish, Washington on October 12-16, 2025, with a quorum present."


def own(claim_id, entity, metric, value, unit, boundary, source, quote, derived, limit, year, note="Generated by scripts/site_count_claims.py."):
    return {**ec.claim(claim_id, entity, metric, value, unit, boundary, source, quote, derived, limit, year), "note": note}


def dataset(title, name, built):
    return {"title": title, "publisher": "ATNI Energy Task Forces", "url": f"{vp.OWN_ORIGIN}data/{name}", "published": built, "kind": "dataset"}


def library_claims(data, script):
    built = data["updated"]
    # shortcut: the address serves the older edition until go-live, so the date is the file's update date and no publication date is claimed; drop PENDING, LIVE and this null after the live file is re-checked.
    source = {**dataset(f"ATNI Energy Task Forces library: public dataset (library.json, updated {ec.us(built)})", "library.json", built), "published": None}
    made = []
    for row in strip.counts(data, script):
        if row["n"]:
            made.append(own(row["id"], "Library entries", row["label"], row["n"], "entry" if row["n"] == 1 else "entries", f"Counted: {row['counted']}, in the edition of library.json updated {ec.us(built)}, the file this release ships. Not counted: sources the library does not hold.",
                            source, f'"updated": "{built}"', f"Count of those entries in library.json, updated {ec.us(built)}.", f"{LIMITS[row['name']]} {DATED} {LIVE}", int(built[:4]), note=PENDING))
    return made


def policy_claims(data):
    built, source = data["generated"], dataset("Policy Watch: public dataset (policy-watch.json)", "policy-watch.json", data["generated"])
    forces = data["task_forces"].values()
    followed = [item["identifier"] for force in forces for item in force["follow"]]
    if len(set(followed)) != len(followed):
        raise SystemExit("An item is on two follow lists, so summing the lists would count it twice: count identifiers, and rewrite lc-051's boundary.")
    follow = len(followed)
    searches = [search for force in forces for search in force["searches"]]
    skipped = sum(search["checked"]["status"] == "unchecked" for search in searches)
    quote = f'"generated": "{built}"'
    return [
        own("lc-051", "Policy Watch", "items followed", follow, "items", f"Counted: every bill, docket, document, and rule identifier on the three task forces' follow lists in policy-watch.json on {ec.us(built)}. No item is on two lists.", source, quote,
            f"Count of follow rows in policy-watch.json, built {ec.us(built)}.", "A count of a curated list, not of all activity on these subjects; following an item endorses nothing.", int(built[:4])),
        own("lc-052", "Policy Watch", "saved searches", len(searches), "searches", f"Counted: every saved search on the three task forces' lists in policy-watch.json on {ec.us(built)}. Not counted: the results of a search.", source, quote,
            f"Count of search rows in policy-watch.json, built {ec.us(built)}; {skipped} of them have the status unchecked.", f"A count of a curated list, not of all sources; {skipped} of these searches use a keyed source and were not run on that date.", int(built[:4])),
    ]


def checklist_claim(page, built):
    block = re.search(r'id="checklists">(.*?)<!-- /SLOT -->', page, re.S)
    if not block:
        raise SystemExit("site/data-centers/index.html has lost its checklists block, so it cannot be counted.")
    lists = re.findall(r'<details class="disclosure" id="q-[a-z]+"', block[1])
    quote = re.search(r'<p class="dc-wide-note">([^<(]*?)\s*\(', page)
    source = {"title": "Data Centers, Questions: the checklists", "publisher": "ATNI Energy Task Forces", "url": f"{vp.OWN_ORIGIN}data-centers/#checklists", "published": built, "kind": "organization"}
    return own("lc-061", "Data Centers page", "checklists", len(lists), "checklists", f"Counted: the checklists in the Questions panel of the Data Centers page on {ec.us(built)}.", source, quote[1], f"Count of the checklist sections in the page, on {ec.us(built)}.",
               "A count of this site's own checklists: questions to put to a proposal, not a review of any proposal and not legal advice.", int(built[:4]))


def whats_new_claim(feed):
    built, source = feed["generated"], dataset("What's New: public dataset (whats-new.json)", "whats-new.json", feed["generated"])
    rows = len(wn.recent(feed["items"], built))
    return own("lc-062", "What's New", "rows in the last ninety days", rows, "rows", f"Counted: rows dated within {feed['window_days']} days of {ec.us(built)} in whats-new.json.", source, f'"generated": "{built}"', f"Count of those rows in whats-new.json, built {ec.us(built)}.",
               "A burst of records from one publisher is one row, so a row count is not a count of records.", int(built[:4]))


def resolution_claim():
    return own("lc-071", "ATNI Resolution #25-41", "year of the convention that adopted it", 2025, "year", "Counted: the year of the Annual Convention named in the certification of the adopted text of Resolution #25-41, as ATNI posts it (10/12/2025 through 10/16/2025, Suquamish, Washington). Not counted: any later action on the resolution.", RES_2541, RES_2541_QUOTE, None, None, 2025,
               note="Generated by scripts/site_count_claims.py. Read 11/05/2026 in ATNI's posted text (the PDF listed as RES_25_41 on atnitribes.org/resolution-table, 2025 Annual Convention). "
                    "The adopted title is 'Establishing an Affiliated Tribes of Northwest Indians (ATNI) Task Force on Data Centers'; Resolution #2026-034 and ATNI's table call it 'For the Development of ...'. "
                    "Published date 2025-10 is the convention month and the PDF's creation month (metadata 10/28/2025); the upload folder is 2025/11.")


def all_claims():
    read = lambda name: json.loads((vp.SITE / "data" / name).read_text(encoding="utf-8"))
    library, script = read("library.json"), strip.SCRIPT.read_text(encoding="utf-8")
    page = (vp.SITE / "data-centers" / "index.html").read_text(encoding="utf-8")
    return [*library_claims(library, script), *policy_claims(read("policy-watch.json")), checklist_claim(page, library["updated"]), whats_new_claim(read("whats-new.json")), resolution_claim()]


def main():
    claims = all_claims()
    ec.write_json(ec.EVIDENCE / "site-counts.json", {"cluster": "site-counts", "claims": claims})
    print(json.dumps({"exported": bp.export_claims(clusters=["site-counts"])}))


if __name__ == "__main__":
    main()
