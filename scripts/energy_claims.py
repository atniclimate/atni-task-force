def checked_dates(programs):
    return sorted({p["status_checked"]["date"] for p in programs})


def dated_rows(data):
    """Programs and live notices with a date, soonest first. A closed program with a date is left out, as it is off the strip."""
    rows = [{"key": p["id"].replace("_", "-"), "program": p["id"], "name": p["short_name"], "iso": p["deadline"]["date"], "what": p["deadline"]["what"], "checked": (p["deadline"].get("checked") or p["status_checked"])["date"],
             "url": (p["deadline"].get("checked") or p["status_checked"])["url"], "quote": (p["deadline"].get("checked") or {}).get("quote"), "agency": p["agency"], "title": p["name"], "status": p["status"], "note": p["status_note"]}
            for p in data["programs"] if (p.get("deadline") or {}).get("date") and p["status"] != "closed"]
    rows += [{"key": f"notice-{o['number'].lower()}", "link": o["url"], "name": o["title"], "iso": o["close_date"], "what": f"Grants.gov notice {o['number']} closes", "checked": data["live"]["retrieved"][:10], "url": o["url"], "quote": None,
              "agency": o["agency"], "title": o["title"], "status": o["status"], "note": o["close_note"] if o.get("close_note") else o["title"]}
             for o in data["live"]["opportunities"] if o.get("close_date")]
    return sorted(rows, key=lambda r: r["iso"])


def undated_programs(data):
    return [p for p in data["programs"] if p["status"] != "closed" and not (p.get("deadline") or {}).get("date")]


