def us(iso):
    return f"{iso[5:7]}/{iso[8:10]}/{iso[:4]}"


def claim(claim_id, entity, metric, value, unit, boundary, source, quote, derived, limit, year, **extra):
    """The project's claim shape. A limit makes it partly verified; none makes it verified."""
    return {"id": claim_id, "entity": entity, "metric": metric, "value": value, "low": None, "high": None, "unit": unit, "year": year, "boundary": boundary, "source": source, "quote": quote,
            "derived": derived, "status": "partly" if limit else "verified", **({"limit": limit} if limit else {}), **extra, "note": "Generated by scripts/energy_claims.py."}


def tribes_word(n):
    return "Tribe" if n == 1 else "Tribes"


