"""Claims and the plate for the county climate plate (Data Centers, Climate tab), the scripts/energy_claims.py pattern. Standard library only.

Reads   site/data/climate-regions.json (scripts/climate_regions.py)
Writes  site/data/plates/dc-climate-counties.json, the plate definition
        work/site-refresh/evidence-n56/climate.json, the evidence file (cluster "climate"); then
        python scripts/build_plates.py --export-claims climate --evidence work/site-refresh/evidence-n56

The plate is drawn first and the claims are minted for exactly the numbers it can show: for each county a record in projects.json
names, and each of the four measures, the 1995 to 2014 level (the first mark) and the 2040 to 2059 level under each scenario (the
second mark). Each figure is the median, lowest, and highest of the seven models' county values in by_model, rounded once, half up,
to the site's two significant figures. Every claim is partly verified with a public limit: no source sentence states a computed number.

    python -B scripts/climate_claims.py
    python -B scripts/climate_claims.py --self-test
"""
import argparse
from decimal import ROUND_HALF_UP, Context
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "site" / "data" / "climate-regions.json"
PLATE_OUT = ROOT / "site" / "data" / "plates" / "dc-climate-counties.json"
# shortcut: Session B's own evidence folder, so a full export from work/site-refresh/evidence/ never picks this file up mid-run; move it there at the merge.
EVIDENCE_OUT = ROOT / "work" / "site-refresh" / "evidence-n56" / "climate.json"
PLATE_ID = "dc-climate-counties"
DEFAULT_ROW = "walla-walla-wa"
DEFAULT_METRIC = "tmax_summer"
STOPS = ("baseline", "ssp245", "ssp370")
METRIC_ORDER = ("tmax_summer", "tmax_annual", "days_95", "pr_annual")

UNITS = {"degF": "F", "days a year": "days a year", "inches": "inches"}
WORDS = {"tmax_annual": "annual mean daytime high", "tmax_summer": "May to September daytime high", "days_95": "count of days at or above 95 F",
         "pr_annual": "annual precipitation"}
AXIS = {"tmax_annual": "Degrees F, annual mean daytime high, county mean", "tmax_summer": "Degrees F, May to September daytime high, county mean",
        "days_95": "Days a year at or above 95 F, county mean", "pr_annual": "Inches a year, precipitation, county mean"}
STEP = {"degF": 5, "days a year": 10, "inches": 10}
SCEN_LABEL = {"ssp245": "SSP2-4.5, lower emissions", "ssp370": "SSP3-7.0, higher emissions"}
MODELS_SAY = "the median and range of seven of eight planned NASA-downscaled models, on a 0.25-degree grid averaged over the county"
LIMIT = {  # one sentence set per variable; it repeats on every receipt, so every word costs 528 times
    "tasmax": f"Model projections, not observations: {MODELS_SAY}. Highs ran 1 to 3 F warm against NOAA station normals in two counties. Research data, not siting guidance.",
    "pr": f"Model projections, not observations: {MODELS_SAY}. Precipitation ran 20 to 25 percent off NOAA station normals in two counties. Research data, not siting guidance.",
}
NOTE = "Generated by scripts/climate_claims.py."
EM_DASH = re.compile("[—–]")


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def sig(v):
    """Once, half up, from the figure as by_model records it: two significant figures, three at 99.5 and up (build_plates.rounded on the decimal text)."""
    if v == 0:
        return 0
    d = Context(prec=3 if abs(v) >= 99.5 else 2, rounding=ROUND_HALF_UP).create_decimal(repr(v))
    return int(d) if d == d.to_integral_value() else float(d)


def spread(values):
    """Median, lowest, and highest of an odd count of model values."""
    s = sorted(values)
    assert len(s) % 2 == 1, "the median of an even count would be a new number"
    return s[len(s) // 2], s[0], s[-1]


def self_test():
    assert sig(84.45) == 84 and sig(84.5) == 85 and sig(0.455) == 0.46 and sig(1.45) == 1.5 and sig(99.5) == 99.5 and sig(102.45) == 102 and sig(0) == 0
    assert sig(14.95) == 15 and sig(-0.25) == -0.25 and isinstance(sig(87.0), int)
    assert spread([3, 1, 2, 7, 5, 4, 6]) == (4, 1, 7)
    return True


def key_of(r):
    return f"{slug(r['county'])}-{r['state'].lower()}"


def mint(data, regions):
    """Claims in a fixed order (county by FIPS, measure, then baseline, ssp245, ssp370) and the ids the plate needs."""
    m = data["method"]
    conversion = {"tasmax": "F = degC x 9/5 + 32", "pr": "inches = mm / 25.4"}
    source = {k: data["source"][k] for k in ("title", "publisher", "url", "published", "kind")}
    quote = data["source"]["resolution"]  # the Tech Note line the boundary's 25 km cell rests on
    claims, ids, n = [], {}, 0
    for r in sorted(regions, key=lambda r: r["fips"]):
        key, county = key_of(r), f"{r['county']} County, {r['state']}"
        cells = f"{r['n_cells']} grid cell{'s' if r['n_cells'] != 1 else ''}"
        boundary = (f"Counted: the mean over {cells} whose centres fall in {county}, seven models with equal weight. "
                    "Not counted: any site, any Nation's land, anything finer than a 25 km cell.")
        for metric in METRIC_ORDER:
            meta = data["metrics"][metric]
            variable = "pr" if metric == "pr_annual" else "tasmax"
            for stop in STOPS:
                n += 1
                cid = f"cp-{n:03d}"
                ids[(key, metric, stop)] = cid
                years, run, year = ("1995 to 2014", "historical run", 2014) if stop == "baseline" else ("2040 to 2059", m["scenarios"][stop], 2059)
                models = r["by_model"][stop][metric]
                med, lo, hi = spread(models)
                unit = UNITS[meta["unit"]]
                derived = (f"Daily {variable}, {run}, {years}, over {cells} at equal weight; {conversion[variable]}; method in climate-regions.json. "
                           f"Seven model values: {', '.join(f'{v:g}' for v in models)} {unit}. Median {med:g}, lowest {lo:g}, highest {hi:g}, rounded once, half up.")
                claims.append({"id": cid, "entity": county, "metric": f"{meta['label']}, {years}, {run}, median of seven models",
                               "value": sig(med), "low": sig(lo), "high": sig(hi), "unit": unit, "year": year, "boundary": boundary, "source": source,
                               "quote": quote, "derived": derived, "status": "partly", "limit": LIMIT[variable], "note": NOTE})
    return claims, ids


def domain_of(claims, unit):
    step = STEP[unit]
    lo = min(c["low"] for c in claims)
    hi = max(c["high"] for c in claims)
    return [max(0, int(lo // step * step)), int(-(-hi // step) * step)]


def plate(data, regions, ids, claims):
    by_id = {c["id"]: c for c in claims}
    regions = sorted(regions, key=lambda r: (not r["data_center_50mw"], r["state"], r["county"]))  # the default view's counties lead, so print and no-script read the same way
    rows, by_row = [], {}
    for r in regions:
        key = key_of(r)
        mine = [ids[(key, m, s)] for m in METRIC_ORDER for s in STOPS]
        shown = {ids[(key, DEFAULT_METRIC, s)] for s in STOPS}
        base = ids[(key, DEFAULT_METRIC, "baseline")]
        rows.append({"id": key, "label": f"{r['county']} County, {r['state']}", "tag": r["state"],
                     "pair": [{"id": "base", "name": "1995 to 2014, historical run", "claims": {"ssp245": base, "ssp370": base}},
                              {"id": "fut", "name": "2040 to 2059, median of seven models", "claims": {s: ids[(key, DEFAULT_METRIC, s)] for s in ("ssp245", "ssp370")}}],
                     "cites": [c for c in mine if c not in shown]})
        by_row[key] = {m: {s: ids[(key, m, s)] for s in STOPS} for m in METRIC_ORDER}
    metrics = {}
    for m in METRIC_ORDER:
        meta = data["metrics"][m]
        metrics[m] = {"label": meta["label"], "words": WORDS[m], "unit": UNITS[meta["unit"]], "axis": AXIS[m], "step": STEP[meta["unit"]],
                      "domain": domain_of([by_id[ids[(key_of(r), m, s)]] for r in regions for s in STOPS], meta["unit"])}
    ww_base, ww_fut = ids[(DEFAULT_ROW, DEFAULT_METRIC, "baseline")], ids[(DEFAULT_ROW, DEFAULT_METRIC, "ssp245")]
    states = sorted({r["state"] for r in regions})
    dc = [key_of(r) for r in regions if r["data_center_50mw"]]
    return {
        "schema": 1, "tier": "T0", "id": PLATE_ID, "page": "data-centers/index.html", "fit": True,
        "eyebrow": "Downscaled projections, NASA NEX-GDDP-CMIP6 v2, built 11/2026",
        "title": f"Walla Walla County's May to September daytime high averages about {{c[{ww_fut}][value]:.0f}} F in 2040 to 2059, up from {{c[{ww_base}][value]:.0f}} F",
        "subtitle": "County means on NASA's quarter-degree grid from seven global models; the figures in parentheses are the lowest and highest model.",
        "text": ["The first view lists the counties where public filings name a data center proposal of fifty megawatts or more. Pick a state for every "
                 "county with a named proposal on the Land tab."],
        "boundary": "County means from a global downscaled dataset. They say nothing about any site, any Nation's land, or what should be built.",
        "controls": [
            {"type": "segmented", "name": "cc_scenario", "label": "Scenario", "default": "ssp245",
             "options": [{"value": s, "label": SCEN_LABEL[s]} for s in ("ssp245", "ssp370")]},
            {"type": "segmented", "name": "cc_metric", "label": "Measure", "default": DEFAULT_METRIC,
             "options": [{"value": m, "label": data["metrics"][m]["label"]} for m in METRIC_ORDER]},
            {"type": "segmented", "name": "cc_state", "label": "Counties", "default": "dc",
             "options": [{"value": "dc", "label": "Data center proposals"}, *({"value": s.lower(), "label": s} for s in states)]},
        ],
        "by": "cc_scenario",
        "plot": {"type": "ladder", "domain": metrics[DEFAULT_METRIC]["domain"], "axis_label": AXIS[DEFAULT_METRIC]},
        "default": DEFAULT_ROW,
        "reading_group": ("{label}: the May to September daytime high averages about {fut} F in 2040 to 2059, the median of seven models "
                          "with the lowest and highest in parentheses, against {base} F in 1995 to 2014. A county mean on a quarter-degree grid; research "
                          "data, not siting guidance."),
        "rows": rows,
        "details": [
            data["source"]["acknowledgement"],
            "NASA's own words on use: “" + data["source"]["recommended_use"] + "”",
            "Seven global models: ACCESS-ESM1-5, CNRM-ESM2-1, EC-Earth3, GFDL-ESM4, GISS-E2-1-G, MIROC6, and MRI-ESM2-0. An eighth planned model, "
            "MPI-ESM1-2-HR, was left out to fit a download cap.",
            "At 2040 to 2059 the two scenarios barely differ, and in some counties the higher-emissions median is the cooler of the two.",
            "Each county's figure is the plain mean of the grid cells whose centres fall inside it, after each cell's own count or mean is taken. Checked "
            "against NOAA's 1991 to 2020 station normals in two counties, the 1995 to 2014 daytime highs ran warmer than the station, and precipitation "
            "ran drier in one county and wetter in the other.",
        ],
        "foot": [{"text": "Every county, measure, and scenario, with each model's own figure.", "href": "../data/climate-regions.json", "link": "climate-regions.json"},
                 {"text": "What a county mean cannot say about water at a site is on the Questions tab.", "href": "#q-water", "link": "Water checklist"}],
        "measures": {"metrics": metrics, "default": DEFAULT_METRIC, "scenarios": SCEN_LABEL, "dc": dc, "rows": by_row},
    }


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    self_test()
    if a.self_test:
        print(json.dumps({"self_test": "passed"}))
        return
    data = json.loads(DATA.read_text(encoding="utf-8"))
    regions = [r for r in data["regions"] if r["named_in_projects"]]
    claims, ids = mint(data, regions)
    defn = plate(data, regions, ids, claims)
    text = json.dumps([claims, defn], ensure_ascii=False)
    assert not EM_DASH.search(text), "em or en dash in our own words"
    assert len({c["id"] for c in claims}) == len(claims) == len(regions) * len(METRIC_ORDER) * len(STOPS)
    cited = {c for row in defn["rows"] for c in row["cites"]} | {m["claims"][s] for row in defn["rows"] for m in row["pair"] for s in m["claims"]}
    assert cited == {c["id"] for c in claims}, "every minted claim must reach the plate, and only those"
    assert DEFAULT_ROW in defn["measures"]["dc"]
    write_json(EVIDENCE_OUT, {"cluster": "climate", "tier": "T0", "schema": 1, "retrieved": "2026-11-05",
                              "data_sha256": hashlib.sha256(DATA.read_bytes()).hexdigest(), "claims": claims})
    write_json(PLATE_OUT, defn)
    print(json.dumps({"claims": len(claims), "rows": len(defn["rows"]), "dc_rows": len(defn["measures"]["dc"]),
                      "domains": {m: v["domain"] for m, v in defn["measures"]["metrics"].items()}}))


if __name__ == "__main__":
    main()
